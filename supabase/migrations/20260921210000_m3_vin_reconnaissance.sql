-- =====================================================================
-- Mission 06, carte 4 — Reconnaître exactement la moto du client par son VIN (hors ligne).
--
-- Le DMS n'interroge pas l'e-catalog Ducati. On a fait reconnaître 3 144 VIN du parc par
-- l'e-catalog (2 975 reconnus) et on en a tiré une TABLE DE CORRESPONDANCE :
--   motif = caractères 1 à 9 du VIN (constructeur + descripteur) + caractère 10 (année)
--   → modèle-année du catalogue, nombre de motos vues, plage de n° de série ARRONDIE à la centaine.
-- Aucune donnée personnelle : jamais de VIN complet, jamais de lien vers un client.
--
--   * ducati_vin_patterns     : la table de correspondance (référentiel constructeur, global).
--   * ducati_vin_model_specs  : caractéristiques par modèle-année (cylindrée, kW, CV, cylindres,
--                               norme), agrégées depuis le parc (valeur la plus fréquente, sans VIN).
--   * _vin_identify_core(vin) : reconnaissance (même logique que src/lib/vin-identify.ts).
--   * vin_identify(vin)       : appelable par tout compte connecté (équipe et espace client) :
--                               marque, année, usine, famille, cylindrée, modèle, version,
--                               modèle-année, confiance, candidats, caractéristiques, nombre de
--                               vues éclatées, plans d'entretien rattachés.
--   * trg_vehicles_catalog_from_vin : à l'enregistrement d'une moto, si `ducati_model_year_id` est
--       vide et que la reconnaissance est « unique », il est rempli (events
--       `vehicle_catalog_linked`, origine system). Un choix fait à l'écran est tracé
--       (`vehicle_catalog_set`). Jamais d'écrasement d'une valeur déjà présente.
--
-- Confiance (validation croisée, 2 970 VIN : on retire chaque VIN et on le reconnaît avec les autres) :
--   unique    : un seul modèle-année connu pour ce motif, vu ≥ 5 fois → 94,9 % exact ;
--   probable  : un seul modèle-année peu vu, ou n° de série dans la plage d'un seul candidat → 79,6 % ;
--   plusieurs : versions d'un même modèle, liste à choisir → bon choix dans la liste 95,5 % ;
--   modele    : descripteur vu d'autres années → cylindrée sûre, modèles projetés sur l'année ;
--   famille   : seule la famille est sûre ; inconnu : rien.
--   Global : famille 99,4 %, cylindrée 97,9 %, version 71,5 %, modèle-année exact 70,1 %,
--   bon modèle-année dans la liste proposée 92,2 %.
--
-- Additif et non destructif. Les données chargées ne concernent que des modèles-années présents
-- dans le catalogue (jointure). Régénérer : `bun tools/vin-patterns/build.ts` (voir l'en-tête).
-- =====================================================================

create table if not exists public.ducati_vin_patterns (
  pattern        text not null check (pattern ~ '^[A-HJ-NPR-Z0-9]{10}$'),  -- VIN 1-9 + 10
  model_year_id  text not null references public.ducati_catalog_model_years(id) on delete cascade,
  serial_from    integer not null default 0,        -- plage de série arrondie (centaine)
  serial_to      integer not null default 999999,
  samples        integer not null default 1 check (samples >= 0),
  updated_at     timestamptz not null default now(),
  primary key (pattern, model_year_id)
);
create index if not exists idx_ducati_vin_patterns_vds on public.ducati_vin_patterns(left(pattern, 9));
comment on table public.ducati_vin_patterns is 'Mission 06 carte 4 : motif de VIN (caractères 1-9 + année) → modèle-année du catalogue Ducati. Référentiel constructeur sans donnée personnelle (pas de VIN complet, plages de série arrondies à la centaine).';

create table if not exists public.ducati_vin_model_specs (
  model_year_id    text primary key references public.ducati_catalog_model_years(id) on delete cascade,
  displacement_cc  numeric,
  power_kw         numeric,
  power_cv         numeric,
  cylinders        integer,
  euro             text,
  samples          integer not null default 0,
  updated_at       timestamptz not null default now()
);
comment on table public.ducati_vin_model_specs is 'Mission 06 carte 4 : caractéristiques techniques par modèle-année (valeur la plus fréquente du parc, sans VIN).';

-- Référentiel global (comme ducati_vds, ducati_catalog_*) : pas de company_id, lecture par
-- l'équipe ; les clients passent par vin_identify. Écriture : migrations / clé de service.
alter table public.ducati_vin_patterns enable row level security;
alter table public.ducati_vin_model_specs enable row level security;
drop policy if exists ducati_vin_patterns_read on public.ducati_vin_patterns;
create policy ducati_vin_patterns_read on public.ducati_vin_patterns
  for select to authenticated using ((select public.ducati_catalog_is_staff()));
drop policy if exists ducati_vin_model_specs_read on public.ducati_vin_model_specs;
create policy ducati_vin_model_specs_read on public.ducati_vin_model_specs
  for select to authenticated using ((select public.ducati_catalog_is_staff()));
revoke all on public.ducati_vin_patterns, public.ducati_vin_model_specs from anon;
revoke insert, update, delete, truncate on public.ducati_vin_patterns, public.ducati_vin_model_specs from authenticated;

